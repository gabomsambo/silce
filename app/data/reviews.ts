function shippedRatingMean(): number {
  const sum = REVIEWS.reduce((acc, review) => acc + review.overallRating, 0);
  return sum / REVIEWS.length;
}

// Derived from REVIEWS at module load, not asserted literals.
// `reviews` is REVIEWS.length. `rating` is the unrounded mean of those
// overallRating integers (574/118 ≈ 4.864407). Display uses two decimals
// (4.86): nothing else on the site renders a decimal rating, and two
// decimals is more precise than the equally honest one-decimal 4.9.
// Hospitable returned no Booking.com, VRBO, or Google reviews.
export const PLATFORM_STATS = [
  {
    platform: "Airbnb",
    rating: shippedRatingMean(),
    reviews: REVIEWS.length,
    logo: "🏠",
  },
];

// Helper functions
export const getAverageRating = () => {
  return shippedRatingMean().toFixed(2);
};

export const getReviewsByProperty = (propertySlug: string) => {
  return REVIEWS.filter((review) => review.propertySlug === propertySlug);
};

export const getReviewsByPlatform = (platform: ReviewPlatform) => {
  return REVIEWS.filter((review) => review.platform === platform);
};

export const getReviewsByRating = (minRating: number) => {
  return REVIEWS.filter((review) => review.overallRating >= minRating);
};

// Sort reviews by date (newest first)
export const getReviewsSortedByDate = () => {
  return [...REVIEWS].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime(),
  );
};

// Published review count: the length of REVIEWS, not the raw API record count.
export const getTotalReviewCount = (): number => {
  return REVIEWS.length;
};
